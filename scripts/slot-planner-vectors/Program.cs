// One-off generator for src/testing/fixtures/slot-planner-vectors.json.
// It runs the backend's real SlotPlanner (Availability.Domain) over a fixed list of cases and
// writes what it would create before overlap checks. See src/testing/fixtures/README.md.
using System.Text.Json;
using System.Text.Json.Serialization;
using Availability.Domain.Entities;

var output = args.Length > 0 ? args[0] : "slot-planner-vectors.json";

WorkingHours H(DayOfWeek d, string opens, string closes) =>
    new(d, TimeOnly.ParseExact(opens, "HH:mm"), TimeOnly.ParseExact(closes, "HH:mm"));

DayOfWeek[] all = Enum.GetValues<DayOfWeek>();
DayOfWeek[] weekdays = [DayOfWeek.Monday, DayOfWeek.Tuesday, DayOfWeek.Wednesday, DayOfWeek.Thursday, DayOfWeek.Friday];

WorkingHours[] Every(string opens, string closes, DayOfWeek[]? days = null) =>
    (days ?? all).Select(d => H(d, opens, closes)).ToArray();

var cases = new List<Case>
{
    new("Europe/London spring forward 2026-03-29 (01:00 does not exist)", "Europe/London",
        Every("00:00", "06:00"), 30, "2026-03-28", "2026-03-30", "2026-01-01T00:00:00Z"),
    new("Europe/London fall back 2026-10-25 (01:00 occurs twice)", "Europe/London",
        Every("00:00", "04:00"), 30, "2026-10-24", "2026-10-26", "2026-01-01T00:00:00Z"),
    new("America/New_York spring forward 2026-03-08", "America/New_York",
        Every("00:00", "05:00"), 30, "2026-03-07", "2026-03-09", "2026-01-01T00:00:00Z"),
    new("America/New_York fall back 2026-11-01", "America/New_York",
        Every("00:00", "05:00"), 30, "2026-10-31", "2026-11-02", "2026-01-01T00:00:00Z"),
    new("Pacific/Auckland spring forward 2026-09-27", "Pacific/Auckland",
        Every("00:00", "05:00"), 60, "2026-09-26", "2026-09-28", "2026-01-01T00:00:00Z"),
    new("Asia/Kolkata half-hour zone, 45 minute service", "Asia/Kolkata",
        Every("09:00", "17:30"), 45, "2026-10-05", "2026-10-11", "2026-01-01T00:00:00Z"),
    new("Asia/Colombo duration does not divide the interval", "Asia/Colombo",
        Every("09:00", "17:00"), 50, "2026-10-05", "2026-10-07", "2026-01-01T00:00:00Z"),
    new("31 dates (30 days apart), weekdays only", "Asia/Colombo",
        Every("08:30", "12:00", weekdays), 30, "2026-10-12", "2026-11-11", "2026-01-01T00:00:00Z"),
    new("now is mid-day today in the branch zone", "America/New_York",
        Every("09:00", "17:00"), 60, "2026-10-05", "2026-10-07", "2026-10-05T18:30:00Z"),
    new("now is exactly a slot start (that slot is dropped)", "UTC",
        Every("09:00", "12:00"), 30, "2026-10-05", "2026-10-05", "2026-10-05T10:00:00Z"),
    new("closed days in the range, different hours per day", "Europe/London",
        [H(DayOfWeek.Monday, "10:00", "12:00"), H(DayOfWeek.Wednesday, "13:00", "15:30"), H(DayOfWeek.Sunday, "09:00", "09:30")],
        30, "2026-10-05", "2026-10-18", "2026-01-01T00:00:00Z"),
    new("single slot fills the interval; interval shorter than the service", "UTC",
        [H(DayOfWeek.Monday, "09:00", "10:00"), H(DayOfWeek.Tuesday, "09:00", "09:20")],
        60, "2026-10-05", "2026-10-06", "2026-01-01T00:00:00Z"),
    new("range wholly in the past", "UTC",
        Every("09:00", "17:00"), 30, "2026-10-05", "2026-10-06", "2026-12-01T00:00:00Z"),
};

var vectors = new List<object>();
foreach (var c in cases)
{
    var branch = Branch.Create("VEC", "Vector", null, "Address", "+14155550123");
    branch.SetSchedule(c.Zone, c.Hours);
    var service = ServiceType.Create("VEC", "Vector", null, c.Duration);
    var from = DateOnly.Parse(c.From);
    var to = DateOnly.Parse(c.To);
    var now = DateTime.Parse(c.NowUtc, null, System.Globalization.DateTimeStyles.AdjustToUniversal);

    var created = SlotPlanner.Plan(branch, service, from, to, 1, now).Count;
    var ignoringNow = SlotPlanner.Plan(branch, service, from, to, 1, DateTime.MinValue.AddYears(1)).Count;
    var days = to.DayNumber - from.DayNumber + 1;
    var closed = Enumerable.Range(0, days)
        .Count(i => branch.WorkingHours.All(w => w.DayOfWeek != from.AddDays(i).DayOfWeek));

    vectors.Add(new
    {
        name = c.Name,
        timeZoneId = c.Zone,
        hours = branch.WorkingHours
            .OrderBy(w => WorkingHours.MondayFirstOrder(w.DayOfWeek))
            .Select(w => new { dayOfWeek = w.DayOfWeek.ToString(), opensAt = w.OpensAt.ToString("HH:mm"), closesAt = w.ClosesAt.ToString("HH:mm") }),
        durationMinutes = c.Duration,
        fromDate = c.From,
        toDate = c.To,
        nowUtc = c.NowUtc,
        expected = new { days, slots = created, closedDays = closed, droppedPast = ignoringNow - created },
    });
}

var json = JsonSerializer.Serialize(
    new
    {
        comment = "Generated by scripts/slot-planner-vectors against the backend SlotPlanner. Do not edit by hand.",
        generatedBy = "Availability.Domain.Entities.SlotPlanner.Plan",
        vectors,
    },
    new JsonSerializerOptions { WriteIndented = true, DefaultIgnoreCondition = JsonIgnoreCondition.Never });
File.WriteAllText(output, json + Environment.NewLine);
Console.WriteLine($"Wrote {vectors.Count} vectors to {Path.GetFullPath(output)}");

record Case(string Name, string Zone, WorkingHours[] Hours, int Duration, string From, string To, string NowUtc);
